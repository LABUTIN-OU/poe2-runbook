"""Версия программы: «<версия игры>.<номер сборки>» — например 0.5.5.4.

Первые три числа — версия игры, под которую программа сделана: её данные (базы, тиры аффиксов, зоны, названия на
девяти языках) взяты из игры этой версии. Последнее число — номер нашей сборки для этой версии игры. Вышла новая
версия игры — выходит новая программа, счёт сборок начинается с 1; под прежние версии игры программа не обновляется
(их слова 2026-11-25: «выход каждой новой версии — мы будем выпускать обновление и не поддерживать старые версии,
поэтому нужно знать, какая у тебя и под какую версию эта программа была установлена»).

Версию игры в номере никто не пишет рукой: она берётся из каталога данных игры, который лежит в самой программе
(catalog/data/current.txt, например 0.5.5.10 -> 0.5.5), — номер не может разойтись с данными. Здесь хранится только
счётчик сборок (BUILD) и версия игры, для которой он считается (GAME): сборщик (packaging/build.py) не соберёт
программу, пока после смены версии игры в каталоге их не поправили.

Какая игра у игрока, говорит сама игра: при каждом запуске она пишет в свой лог строку
    [HTTP2] User agent: PoE poe2_production/tags/0.5.5h Windows x64
(проверено на логе за семь месяцев: 74 запуска — 74 строки). Буква — исправление внутри версии (f, g, h…): номер
программы от неё не зависит. До ноября 2026 клиент называл ту же версию с четвёркой впереди (4.5.2 — это 0.5.2):
stem() приводит обе записи к одной. У файла программы игры версии нет, в Steam — только номер сборки без версии.
"""
import re

GAME = '0.5.5'      # версия игры, для которой считается BUILD
BUILD = 23          # номер сборки программы для этой версии игры (0.1.0, 0.2.0 и 0.2.1 были первыми тремя)

# строка лога, в которой игра называет свою версию; реплика в чате такой строкой не притворится: у неё после
# «[INFO Client N]» идёт имя игрока
RE_GAME_TAG = re.compile(r'\[INFO Client \d+\] \[HTTP2\] User agent: PoE \S+/tags/([0-9A-Za-z._-]{1,24})')


def stem(version):
    """Версия игры тремя числами: '0.5.5.10' -> '0.5.5', '0.5.5h' -> '0.5.5', '4.5.2' -> '0.5.2'. Не версия — None."""
    m = re.match(r'\s*(\d+)\.(\d+)\.(\d+)', str(version or ''))
    if not m:
        return None
    major, minor, patch = (int(x) for x in m.groups())
    if major == 4:
        major = 0       # прежняя запись версии PoE2 в логе клиента: 4.5.2 = 0.5.2
    return '%d.%d.%d' % (major, minor, patch)


def program(catalog_version, build=BUILD):
    """Версия программы по версии каталога данных игры: '0.5.5.10' -> '0.5.5.4'. Каталога нет — None."""
    game = stem(catalog_version)
    return '%s.%d' % (game, build) if game else None


def newer(game, catalog_version):
    """Игра у игрока (как её назвал лог, '0.6.0b') новее той, под которую сделана программа. Чего-то не знаем — нет."""
    have, made = stem(game), stem(catalog_version)
    if not have or not made:
        return False
    return tuple(int(x) for x in have.split('.')) > tuple(int(x) for x in made.split('.'))


def game_tag(line):
    """Версия игры из строки её лога ('0.5.5h'); строка не о версии — None."""
    if 'tags/' not in line:
        return None
    m = RE_GAME_TAG.search(line)
    return m.group(1) if m else None
